#!/usr/bin/env python3
"""Summarise results/artifacts (downloaded by collect_results.py) into results/summary.md.
Everything is computed from the real artifacts (state.json, usage.jsonl, verdict.json)."""
import json
from collections import Counter, defaultdict
from pathlib import Path

ART = Path(__file__).resolve().parent.parent / "results" / "artifacts"
OUT = ART.parent / "summary.md"

runs, reviews = [], []
tokens = Counter()
calls = Counter()
for run_dir in sorted(ART.iterdir()):
    for a in run_dir.iterdir():
        st, vj = a / "state.json", a / "verdict.json"
        if st.exists():
            s = json.loads(st.read_text())
            s["run_id"] = run_dir.name
            s["duration_min"] = round((s["history"][-1]["t"] if s["history"] else 0) / 60, 1)
            runs.append(s)
        if vj.exists():
            v = json.loads(vj.read_text())
            v["run_id"] = run_dir.name
            reviews.append(v)
        uj = a / "usage.jsonl"
        if uj.exists():
            for line in uj.read_text().splitlines():
                if line.strip():
                    r = json.loads(line)
                    tokens[r["model"]] += r["total"]
                    calls[r["model"]] += 1

L = ["# Results summary (generated by tools/summarize.py from results/artifacts)", ""]
L += ["## Pipeline runs (agents job)", "",
      "| Run | Issue | Variant | Round | Status | Stopped at / reason | Spec attempts | Design pass | Builder attempts | Transitions | Tokens | Minutes |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for s in sorted(runs, key=lambda s: (s["issue"], s["variant"], s["run_id"])):
    st = s["stages"]
    L.append(f"| {s['run_id']} | #{s['issue']} | {s['variant']} | {s['round']} | {s['status']} | "
             f"{s.get('stopped_stage', '')} {s.get('stopped_reason', '')[:70].replace('|', '/')} | "
             f"{st.get('spec', {}).get('attempt', '-')} | {st.get('design', {}).get('pass', '-')} | "
             f"{st.get('test', {}).get('attempt', '-')} | {' > '.join(h['to'] for h in s['history'])} | "
             f"{s.get('tokens_total', 0):,} | {s['duration_min']} |")

L += ["", "## Reviews", "", "| Run | PR | Issue | Variant | Model | Verdict | Target | Ran tests | Guard | Tokens |",
      "|---|---|---|---|---|---|---|---|---|---|"]
for v in sorted(reviews, key=lambda v: (v["pr"], v["variant"])):
    L.append(f"| {v['run_id']} | #{v['pr']} | #{v['issue']} | {v['variant']} | {v['model']} | {v['verdict']} | "
             f"{v.get('target', '')} | {v.get('ran_tests')} | {v.get('guard', '')[:40]} | {v.get('tokens', 0):,} |")

L += ["", "## Model usage (all downloaded usage.jsonl)", "", "| Model | Calls | Tokens |", "|---|---|---|"]
for m, t in tokens.most_common():
    L.append(f"| {m} | {calls[m]} | {t:,} |")
L.append(f"| **total** | **{sum(calls.values())}** | **{sum(tokens.values()):,}** |")
OUT.write_text("\n".join(L) + "\n")
print(OUT.read_text())
